def _to_api_messages(history: Iterable[Message]) -> list[dict[str, str]]:
    """История из БД → `input` для Responses API.

    Первое сообщение должно быть от пользователя, поэтому ведущие ответы
    бота отбрасываются. Пустые сообщения пропускаются.
    """
    messages: list[dict[str, str]] = []
    for item in history:
        content = (item.content or "").strip()
        if not content:
            continue
        if not messages and item.role != "user":
            continue
        messages.append({"role": item.role, "content": content})
    return messages


def _total_tokens(response: Any) -> int:
    usage = getattr(response, "usage", None)
    return int(getattr(usage, "total_tokens", 0) or 0)


def _backoff(attempt: int, base: float = 1.5, cap: float = 30.0) -> float:
    """Экспоненциальный backoff с джиттером."""
    return min(base * (2**attempt) + random.uniform(0, 1), cap)


def _retry_after(exc: openai.APIStatusError) -> Optional[float]:
    """Читает заголовок `retry-after`, если он есть."""
    try:
        value = exc.response.headers.get("retry-after")
        return float(value) if value else None
    except (AttributeError, TypeError, ValueError):
        return None


def _mask(url: str) -> str:
    """Прячет креды в URL прокси перед записью в лог."""
    if "@" not in url:
        return url
    scheme, _, rest = url.partition("://")
    _, _, host = rest.rpartition("@")
    return f"{scheme}://***@{host}"
