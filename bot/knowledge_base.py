def find_service(query: str) -> Service | None:
    """Простой поиск услуги по подстроке в названии (для команд/отладки)."""
    needle = query.strip().casefold()
    if not needle:
        return None
    for service in SERVICES:
        if needle in service.name.casefold():
            return service
    return None


def services_summary() -> str:
    """Короткий список услуг с ценами — для команды /help.

    Сроки здесь не печатаются: они длинные и зависят от основания, поэтому
    в справке только выглядели бы шумом. Агент называет их в диалоге.
    """
    return "\n".join(f"• {s.name} — {s.price}" for s in SERVICES)


