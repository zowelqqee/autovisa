def _render_procedure(proc: Procedure) -> list[str]:
    lines = [f"### {proc.name}", proc.summary, ""]
    if proc.steps:
        lines.append("Порядок:")
        lines.extend(f"{i}. {s}" for i, s in enumerate(proc.steps, 1))
    if proc.documents:
        lines.append("Документы:")
        lines.extend(f"- {d}" for d in proc.documents)
    for label, items in proc.variants.items():
        lines.append(f"{label}:")
        lines.extend(f"- {i}" for i in items)
    if proc.timeline:
        lines.append(f"Сроки: {proc.timeline}")
    if proc.state_fee:
        lines.append(f"Государственная пошлина: {proc.state_fee}")
    if proc.ask:
        lines.append(
            "Что может иметь значение (не чек-лист и не анкета — бери отсюда "
            "только то, чего реально не хватает для ответа прямо сейчас; если "
            "клиент уже сказал достаточно, чтобы дать план хотя бы по одной "
            "ветке — отвечай, а не спрашивай остальное из списка):"
        )
        lines.extend(f"- {a}" for a in proc.ask)
    if proc.never_claim:
        lines.append("НЕЛЬЗЯ утверждать:")
        lines.extend(f"- {n}" for n in proc.never_claim)
    if proc.notes:
        lines.append(f"Примечание: {proc.notes}")
    lines.append("")
    return lines


def _render_dict_block(block: dict) -> list[str]:
    lines = [f"### {block['title']}"]
    if "summary" in block:
        lines.append(block["summary"])
    for key, value in block.items():
        if key in ("title", "summary"):
            continue
        lines.append(f"{key}:")
        lines.extend(f"- {item}" for item in value)
    lines.append("")
    return lines


